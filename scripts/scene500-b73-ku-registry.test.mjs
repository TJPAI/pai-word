import assert from 'node:assert/strict';
import {verifyRegistry,planSrsMigration} from './scene500-b73-ku-registry.mjs';
const entry={ku_id:'core20k:ku:000001',word_id:'core20k:w:000001',sense_id:'core20k:s:000001',ku_type:'sense',semantic_key:'lexeme:example:sense1',status:'approved'};
assert.equal(verifyRegistry([entry],['legacy:ku:1']).pass,true);
assert.equal(verifyRegistry([entry,entry]).pass,false);
assert.equal(verifyRegistry([{...entry,ku_id:'legacy:ku:1'}],['legacy:ku:1']).pass,false);
assert.equal(verifyRegistry([{...entry,status:'pending'}]).pass,false);
const initial={'old:1':{reps:3,due:10},'stay:1':{reps:5,due:20},'old:2':{reps:1,due:30}};
const target=['new:1','new:2','stay:1'];
const m=planSrsMigration(initial,['old:1','old:2','stay:1'],target,[{from:'old:1',to:['new:1'],type:'replace'},{from:'old:2',to:['new:2'],type:'split'}]);
assert.equal(m.pass,true);assert.deepEqual(m.records['new:1'],initial['old:1']);
assert.deepEqual(m.records['stay:1'],initial['stay:1']);
assert.equal(m.pending['old:2'].reason,'SPLIT_REQUIRES_EXPLICIT_RESOLUTION');
const noop=planSrsMigration({'stay:1':initial['stay:1']},['stay:1'],['stay:1']);
assert.deepEqual(noop.records['stay:1'],initial['stay:1']);
const lost=planSrsMigration({'unknown:1':{reps:2}},[],[],[]);
assert.deepEqual(lost.pending['unknown:1'].record,{reps:2});
const collision=planSrsMigration({'old:1':initial['old:1'],'new:1':{reps:7}},['old:1'],target,[{from:'old:1',to:['new:1'],type:'replace'}]);
assert.equal(collision.pending['old:1'].reason,'DESTINATION_COLLISION');
const invalid=planSrsMigration(initial,['old:1','old:2','stay:1'],target,[{from:'old:1',to:['absent'],type:'replace'}]);
assert.equal(invalid.pass,false);assert.equal(invalid.unchanged,true);
console.log('B73 registry and SRS migration fixtures PASS');
