import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import {PreviewReader} from './preview-reader.mjs';
const root=process.argv[2];assert(root,'Usage: node test-preview-reader.mjs <shards-directory>');
let reads=0;
const fetcher=async u=>{reads++;const file=path.join(root,u.replace(/^\.\//,''));if(!fs.existsSync(file))return {ok:false};const b=fs.readFileSync(file);return {ok:true,json:async()=>JSON.parse(b),arrayBuffer:async()=>b};};
const digest=async b=>crypto.createHash('sha256').update(b).digest('hex');
const inflate=async b=>zlib.gunzipSync(b);
const r=new PreviewReader({fetcher,digest,inflate});await r.start();
for(const rank of [1,250,251,10000,12990,19999,20000])assert.equal((await r.word(rank)).rank,rank);
const before=reads;await Promise.all([r.word(1),r.word(1),r.word(200)]);assert.equal(reads,before);
assert.equal((await r.word(1)).legacy_quality.release_eligible,false);
const original=fs.readFileSync(path.join(root,'words-01.json.gz'));
const bad=async u=>u.endsWith('words-01.json.gz')?{ok:true,arrayBuffer:async()=>Buffer.concat([original.subarray(0,47),Buffer.from([original[47]^255]),original.subarray(48)])}:fetcher(u);
const corrupted=new PreviewReader({fetcher:bad,digest,inflate});await corrupted.start();
await assert.rejects(corrupted.word(1),/CHUNK_INTEGRITY/);
await assert.rejects(r.word(0),/RANK/);
console.log(JSON.stringify({status:'PASS',ranks:7,cache:r.cache.size,checksumTamperingRejected:true}));
