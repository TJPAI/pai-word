import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {trainTinyRanker} from './tiny-ranker.mjs';
const catalog=JSON.parse(fs.readFileSync(new URL('../../scene500-recommendation/catalog-v0.2.json',import.meta.url)));
const run=(c,d)=>trainTinyRanker(c,{dimension:d,epochs:2}).exportWeights();
const a=run(catalog,1024),b=run(catalog,1024);
assert.equal(a.base64,b.base64,'NONDETERMINISTIC_WEIGHTS');
const bytes=Buffer.from(a.base64,'base64');
assert.equal(bytes.length,500*1024);
const sha256=createHash('sha256').update(bytes).digest('hex');
const example=run({...catalog,scene_count:1500,scenes:{...catalog.scenes,...Object.fromEntries(Array.from({length:1000},(_,i)=>['S'+String(i+501).padStart(4,'0'),{name:'规模测试场景'+(i+501),aliases:[],example_queries:[]}]))}},1024);
const expandedBytes=Buffer.from(example.base64,'base64').length;
assert.equal(expandedBytes,1500*1024);
const max=2_000_000;
const fixedCatalogSize=fs.readFileSync(new URL('../../scene500-recommendation/catalog-v0.2.json',import.meta.url)).length;
const modules=['./microrec.mjs','./intent-aware.mjs','./conservative.mjs','./tiny-ranker.mjs'].reduce((n,p)=>n+fs.readFileSync(new URL(p,import.meta.url)).length,0);
const report={status:expandedBytes+fixedCatalogSize+modules<=max?'PASS':'FAIL',train_reproducible:true,trained500_bytes:bytes.length,trained500_sha256:sha256,synthetic1500_weights_bytes:expandedBytes,base500_catalog_bytes:fixedCatalogSize,modules_bytes:modules,synthetic1500_conservative_lower_bound_bytes:expandedBytes+fixedCatalogSize+modules,limit_bytes:max,notes:'Uses original 500 catalog bytes for synthetic 1500 lower bound; full 1500 data, E5 teacher weights, deployment metadata are excluded. No semantic accuracy claims.'};
console.log(JSON.stringify(report,null,2));
if(report.status!=='PASS')process.exitCode=1;
