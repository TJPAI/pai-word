import {createScene500AI,validateIdentity,fingerprintIdentity} from './scene500-ai-adapter.mjs';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
globalThis.crypto??=webcrypto;
const scenes=Object.fromEntries(Array.from({length:500},(_,i)=>{const id='S'+String(i+1).padStart(3,'0');return [id,{name:i===0?'起床与晨间准备':'场景'+id}]}));
const catalog={scenes};
assert.equal(validateIdentity(catalog),true);
const fp=await fingerprintIdentity(catalog);
assert.match(fp,/^[a-f0-9]{64}$/);
const index={taxonomyVersion:'scene500-taxonomy-20x25-v1',taxonomyFingerprint:fp,scenes:Object.keys(scenes).map((sceneId,i)=>({sceneId,vector:i===0?[1,0]:[0,1]}))};
let loads=0;
const engine=createScene500AI({loadCatalog:async()=>{loads++;return catalog},loadIndex:async()=>index,embedQuery:async()=>[1,0]});
const result=await engine.recommend({query:'早晨起床',topK:5});
assert.equal(result.status,'ok');assert.equal(result.recommendations[0].sceneId,'S001');
assert.equal(result.scoreType,'cosine_similarity');assert.equal(result.modeUsed,'e5');
assert.equal(result.taxonomyFingerprint,fp);
await engine.initialize();assert.equal(loads,1);
assert.equal((await engine.recommend({query:'   '})).status,'invalid_input');
await assert.rejects(engine.recommend({query:'test',signal:AbortSignal.abort()}),{name:'AbortError'});
const fallback=createScene500AI({loadCatalog:async()=>catalog,fallback:async()=>['S002','S002','S001','INVALID']});
const f=await fallback.recommend({query:'hello'});
assert.equal(f.modeUsed,'rules_fallback');assert.deepEqual(f.recommendations.map(x=>x.sceneId),['S002','S001']);
const bad={...index,taxonomyFingerprint:'wrong'};
assert.throws(()=>validateIdentity({...catalog,taxonomyFingerprint:fp},bad));
console.log('PASS adapter schema, 500 identity, SHA-256, index, ranking, lazy load, abort, fallback, dedup');
