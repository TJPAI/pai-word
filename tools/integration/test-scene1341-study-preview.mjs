import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {loadScene1341AuthorPreview,createScene1341ReadOnlySession,renderScene1341ReadOnlyCard,readScene1341PreviewCursor,setScene1341PreviewCursor} from '../../rebuild-preview/scene1341-study-preview.mjs';
const base=new URL('./scene1341-teaching/',import.meta.url);
const fetchFile=async url=>new Response(await fs.readFile(fileURLToPath(url)),{status:200});
const cards=await loadScene1341AuthorPreview({fetchImpl:fetchFile,base});
assert.equal(cards.length,304);
assert.equal(new Set(cards.map(x=>x.id)).size,304);
const first=cards.filter(x=>x.sceneId==='SC50-0001');
const second=cards.filter(x=>x.sceneId==='SC50-0002');
assert.equal(first.length,234);
assert.equal(second.length,70);
for(const group of [first,second])assert(group.every((x,i)=>x.rank===i+1));
let calls=0;
const renderer=u=>{calls++;assert.equal(u.s.kuType,'scene1341');return '<div class="answer">EXAMPLE:'+u.s.e[0]+'</div>'};
for(const [scene,group] of [['SC50-0001',first],['SC50-0002',second]]){
 const model=createScene1341ReadOnlySession(group);
 const initial=model.view();
 assert.equal(initial.index,0);assert.equal(initial.revealed,false);
 assert.equal(initial.canRate,false);assert.equal(initial.canSaveProgress,false);
 const question=renderScene1341ReadOnlyCard(initial,{answerHtml:renderer});
 assert(question.includes(group[0].expression));
 assert(question.includes(scene));
 assert(!question.includes('EXAMPLE:'));
 assert(question.includes('disabled>不知道'));
 const revealed=model.reveal();
 const answer=renderScene1341ReadOnlyCard(revealed,{answerHtml:renderer});
 assert(answer.includes('EXAMPLE:'));
 assert(answer.includes('disabled>知道'));
 assert.equal(model.next().index,1);
 assert.equal(model.view().revealed,false);
 assert.equal(model.previous().index,0);
 assert.equal(model.jump(group.length-1).index,group.length-1);
 assert.throws(()=>model.jump(group.length),/PREVIEW_INDEX/);
 assert.throws(()=>renderScene1341ReadOnlyCard({...revealed,canRate:true},{answerHtml:renderer}),/WRITABLE_REJECTED/);
}
assert.equal(calls,2);
assert.equal(readScene1341PreviewCursor('SC50-0001'),null);
setScene1341PreviewCursor('SC50-0001',first[17].id);
setScene1341PreviewCursor('SC50-0002',second[7].id);
assert.equal(readScene1341PreviewCursor('SC50-0001'),first[17].id);
assert.equal(readScene1341PreviewCursor('SC50-0002'),second[7].id);
assert.throws(()=>setScene1341PreviewCursor('S001','KU-001'),/CURSOR_INVALID/);
const moduleSource=await fs.readFile(new URL('../../rebuild-preview/scene1341-study-preview.mjs',import.meta.url),'utf8');
assert(moduleSource.includes('const savedCursor=readScene1341PreviewCursor(sceneId)'), 'resume entry hook missing');
assert(moduleSource.includes('if(restoreIndex>=0)session.jump(restoreIndex)'), 'cursor restore missing');
assert(!moduleSource.includes('localStorage.'), 'no localStorage method calls in preview');
const home=await fs.readFile(new URL('../../rebuild-preview/home-dashboard.js',import.meta.url),'utf8');
assert(home.includes('openScene1341ReadOnlyPreview'));
assert(home.includes('预览234条答案型词卡（只读审核）'));
assert(home.includes('预览70条答案型词卡（只读审核）'));
assert(!home.includes('scene1341-srs-v2.mjs'),'draft home must not connect to persistence');
console.log(JSON.stringify({status:'PASS',allDrafts:304,scenes:2,first:234,second:70,answerRenderCalls:calls,
 questionMode:'self_recall',gradingDisabled:true,SRSWrites:0}));
