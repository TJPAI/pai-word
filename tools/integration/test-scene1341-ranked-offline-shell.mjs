import assert from 'node:assert/strict';
import fs from 'node:fs';
const home=fs.readFileSync('rebuild-preview/home-dashboard.js','utf8');
const html=fs.readFileSync('rebuild-preview/scene1341-ranked/index.html','utf8');
const sw=fs.readFileSync('rebuild-preview/scene1341-ranked/sw.js','utf8');
assert(home.includes('href="rebuild-preview/index.html?scene1341=1"'),'home link must switch the original UI to Scene1341 mode');
assert(home.includes('现有学习记录保持隔离'),'home link must protect existing learning history');
assert(html.includes('src="../scene1341-ranked-ui.mjs"'));
assert(html.includes('serviceWorker.register("./sw.js",{scope:"./"})'));
assert(!html.includes('onclick="openReview()"'));
assert(sw.includes('rebuild-preview/scene1341-ranked/'),'scope comment');
assert(sw.includes('if(!ALLOWED.has(u)&&!batch)return;'));
assert(sw.includes('DATA_CACHE'));
assert(sw.includes('SHELL_CACHE'));
assert(sw.includes('Offline asset not yet cached'));
assert(!sw.includes('caches.keys()'),'no global cache deletion');
const scope='https://example.test/v22-integration/rebuild-preview/scene1341-ranked/sw.js';
const shell=new URL('./index.html',scope).href;
const outside=new URL('../index.html',scope).href;
const data=new URL('../../tools/integration/scene1341-ranked/v61-ranked.csv',scope).href;
assert(shell.includes('/rebuild-preview/scene1341-ranked/index.html'));
assert(outside.includes('/rebuild-preview/index.html')&&!outside.includes('/scene1341-ranked/index.html'));
assert(data.includes('/tools/integration/scene1341-ranked/v61-ranked.csv'));
console.log('PASS Scene1341 opt-in link + scoped offline shell; existing Scene500 app remains separate');
