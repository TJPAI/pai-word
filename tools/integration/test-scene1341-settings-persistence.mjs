import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../../rebuild-preview/scene1341-readonly/scene500-readonly-settings.js',import.meta.url),'utf8');
const store=new Map();
const localStorage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,String(v))};
const root={localStorage};
vm.runInNewContext(source,{window:root,globalThis:root});
const {createReadOnlySettings,defaults}=root.PAI_SCENE500_READONLY_SETTINGS;
let changes=[];
const settings=createReadOnlySettings({onChange:(key,prefs)=>changes.push([key,prefs])});
assert.equal(settings.get('wordsPerRound'),10);
assert.equal(settings.get('autoPronounce.swipe'),true);
assert.equal(settings.set('wordsPerRound','25'),true);
assert.equal(settings.set('autoPronounce.swipe',false),true);
assert.equal(settings.set('showExamples',false),true);
assert.equal(settings.set('voiceAccent','gb'),true);
assert.equal(settings.set('wordsPerRound',13),false,'reject unsupported round size');
assert.equal(settings.set('unrecognized',true),false,'reject unknown settings');
const second=createReadOnlySettings();
assert.equal(second.get('wordsPerRound'),25,'round size survives reload');
assert.equal(second.get('autoPronounce.swipe'),false,'auto pronunciation survives reload');
assert.equal(second.get('showExamples'),false,'answer visibility survives reload');
assert.equal(second.get('voiceAccent'),'gb');
second.reset();
const third=createReadOnlySettings();
assert.equal(third.get('wordsPerRound'),defaults.wordsPerRound);
assert.equal(third.get('autoPronounce.swipe'),defaults.autoPronounce.swipe);
assert.equal(third.get('showExamples'),defaults.showExamples);
assert.equal(third.get('voiceAccent'),defaults.voiceAccent);
assert.equal(changes.length,4);
assert.ok([...store.keys()].every(k=>k.startsWith('pai-word-scene1341-readonly-')),'isolated namespace only');
console.log('PASS: isolated Scene1341 settings persist, validate, reset and never touch native app/SRS keys');
