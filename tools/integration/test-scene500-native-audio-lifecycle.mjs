import assert from 'node:assert/strict';
import {createNativeScene500AudioProbe as make} from './scene500-native-audio-lifecycle-harness.mjs';
const p=make();const audio=p.window.PAI_AUDIO;
let done=0,idle=0;
assert.equal(audio.isActive(),false);
audio.play('wake up',.84,()=>done++);
assert.equal(audio.isActive(),true);
assert.equal(p.ops.at(-1).lang,'en-US');
assert.equal(p.ops.at(-1).voice,'US Voice');
assert.equal(p.ops.at(-1).rate,.84);
const activeTrace=p.window.PAI_AUDIO_TRACE.at(-1);
assert.equal(activeTrace.status,'requested','Calling synth.speak does NOT prove audible sound');
audio.whenIdle(()=>idle++);
p.synth.utterance.onstart();
assert.equal(activeTrace.status,'started');
p.synth.utterance.onend();
assert.equal(done,1);assert.equal(idle,1);
assert.equal(activeTrace.status,'ended');
assert.equal(audio.isActive(),false);
p.synth.utterance.onend();assert.equal(done,1,'No duplicate completion');
const gb=make({voiceAccent:'gb',speechSpeed:150});let gbDone=0;
gb.window.PAI_AUDIO.play('good morning',.8,()=>gbDone++);
assert.equal(gb.ops.at(-1).lang,'en-GB');
assert.equal(gb.ops.at(-1).voice,'GB Voice');
assert.equal(gb.ops.at(-1).rate,1.2);
gb.synth.utterance.onerror({error:'interrupted'});
assert.equal(gbDone,1);assert.equal(gb.window.PAI_AUDIO_TRACE.at(-1).status,'error');
const replaced=make();let stale=0,fresh=0;
replaced.window.PAI_AUDIO.play('first',.84,()=>stale++);
const old=replaced.synth.utterance;
replaced.window.PAI_AUDIO.play('second',.84,()=>fresh++);
old.onend();
assert.equal(stale,0,'Cancelled previous generation never commits callback');
assert.equal(replaced.window.PAI_AUDIO_TRACE.length,2);
replaced.synth.utterance.onend();
assert.equal(fresh,1);
const watchdog=make();
watchdog.window.PAI_AUDIO.play('stuck speech');
assert.equal(watchdog.window.PAI_AUDIO.isActive(),true);
watchdog.fireWatchdog();
assert.equal(watchdog.window.PAI_AUDIO.isActive(),false);
assert.equal(watchdog.window.PAI_AUDIO_TRACE.at(-1).status,'timeout-before-start');
const resume=make();
resume.window.PAI_AUDIO.play('suspended');
resume.visibility(true);resume.tick(16000);resume.visibility(false);
assert.equal(resume.window.PAI_AUDIO.isActive(),false);
assert.equal(resume.window.PAI_LAST_AUDIO_RESUME.status,'queue-reset');
assert.equal(resume.window.PAI_LAST_AUDIO_RESUME.voiceCount,2);
const short=make();
short.window.PAI_AUDIO.play('quick background');
short.visibility(true);short.tick(14000);short.visibility(false);
assert.equal(short.window.PAI_AUDIO.isActive(),true,'Short background should not force queue reset');
const silent=make({voices:[]});
let silentDone=0;
silent.window.PAI_AUDIO.play('',.84,()=>silentDone++);
assert.equal(silentDone,1);
assert.equal(silent.ops.length,0,'Empty text does not call synthesis');
const fallback=make({voiceAccent:'gb',voices:[{lang:'en-US',name:'US only'}]});
fallback.window.PAI_AUDIO.play('hello');
assert.equal(fallback.ops.at(-1).voice,'US only');
console.log(JSON.stringify({status:'PASS',source:'original Scene500 Web Speech lifecycle',
 checks:['US/GB voice and speed','started-not-audible-proof','end once','error callback',
 'stale generation cancellation','watchdog recovery','15s background reset',
 'short suspension','empty text','voice fallback'],
 srsWrites:0,scene1341Activated:false}));
