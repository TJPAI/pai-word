import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const original=fs.readFileSync('scripts/core20k-approved-overlay-boot.mjs','utf8');
const source=original.replace(/^import .*;$/m,'').replaceAll('export function ','function ').replaceAll('export async function ','async function ').replace(/import\.meta\.url/g,JSON.stringify('https://example.test/scripts/core20k-approved-overlay-boot.mjs'));
const calls=[];
const window={PAI_APPROVED_OVERLAY_CONFIG:{enabled:false},PAI_CORE:{byKU:new Map([['ku',{}]])}};
const installApprovedTeachingOverlay=(result,scope)=>{scope.PAI_APPROVED_TEACHING_OVERLAY=result;return result};
const loadApprovedTeachingOverlay=async()=>({enabled:true,accepted:new Map([['ku',{}]])});
const context={window,URL,Uint8Array,AbortController,TextDecoder,Promise,Map,Array,crypto:webcrypto,installApprovedTeachingOverlay,loadApprovedTeachingOverlay,fetch:url=>new Promise((resolve,reject)=>calls.push({url,resolve,reject}))};
vm.runInNewContext(source+';globalThis.boot=bootApprovedOverlay;',context);
const bytes=x=>new TextEncoder().encode(JSON.stringify(x));
const manifest=bytes({status:'PRODUCTION_READY',activation_allowed:true});
const overlay=bytes({records:[{ku_id:'ku'}]});
const runtime=bytes({runtime:true}),pack=bytes({pack:true});
const sha=async x=>Buffer.from(await webcrypto.subtle.digest('SHA-256',x)).toString('hex');
const valid={enabled:true,mode:'production',manifestUrl:'./manifest.json',overlayUrl:'./overlay.json',packUrl:'./pack.json',manifestSha256:await sha(manifest),overlaySha256:await sha(overlay)};
const respond=(i,data)=>calls[i].resolve({ok:true,arrayBuffer:async()=>data.buffer.slice(data.byteOffset,data.byteOffset+data.byteLength)});
const older=context.boot(valid);
const newer=context.boot(valid);
assert.equal(calls.length,8);
[manifest,overlay,runtime,pack].forEach((x,i)=>respond(4+i,x));
assert.equal((await newer).enabled,true);
const installed=window.PAI_APPROVED_TEACHING_OVERLAY;
assert.equal(installed.accepted.size,1);
calls[0].reject(Error('old network request failed'));
assert.equal((await older).reason,'superseded');
assert.equal(window.PAI_APPROVED_TEACHING_OVERLAY,installed,'older network failure cannot clear successful newer activation');
console.log('PASS newer signed overlay activation survives later failure of older network request');
