import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const path=new URL('../../rebuild-preview/scene1341-readonly/scene500-readonly-phase.js',import.meta.url);
const timers=new Map();let nextTimer=0;
const root={};
const context={window:root,globalThis:root,navigator:undefined,Promise,setTimeout:(fn,ms)=>{const id=++nextTimer;timers.set(id,{fn,ms});return id},clearTimeout:id=>timers.delete(id)};
vm.runInNewContext(readFileSync(path,'utf8'),context,{filename:'scene500-readonly-phase.js'});
const {createReadOnlyPhaseController,createReadOnlyAutoBrowse}=root.PAI_SCENE500_READONLY_PHASE;
let updates=[],graded=0,advanced=0;
const phase=createReadOnlyPhaseController({onUpdate:s=>updates.push({...s}),onGradeComplete:()=>graded++,onAdvance:()=>advanced++});
phase.start('SC1341:1');
assert.equal(phase.state().preferredFace,'question');
phase.tap();
assert.equal(phase.state().preferredFace,'answer');
assert.equal(phase.state().revealed,true);
phase.navigate('SC1341:2');
assert.equal(phase.state().preferredFace,'answer','swipe must preserve answer face');
assert.equal(phase.state().phase,'answer-paused');
phase.navigate('SC1341:3');
assert.equal(phase.state().preferredFace,'answer','auto browse must preserve answer face');
phase.tap();
assert.equal(phase.state().preferredFace,'question');
phase.navigate('SC1341:4');
assert.equal(phase.state().phase,'question','question face persists on next card');
phase.tap();phase.beginExample();phase.exampleFinished();
assert.equal(phase.state().phase,'answer-paused');
phase.navigate('SC1341:5');
assert.equal(phase.state().preferredFace,'answer');
phase.cancel();
assert.equal(phase.state().cardKey,null);
assert.equal(graded,0);assert.equal(advanced,0);
let current=0,autoState=[];
const auto=createReadOnlyAutoBrowse({shouldRun:()=>true,isBusy:()=>false,navigate:()=>{current=(current+1)%3;return true},onState:v=>autoState.push(v)});
auto.setDelay(900);auto.start();
assert.equal(auto.isEnabled(),true);
let t=[...timers.values()].find(x=>x.ms===900);
assert.ok(t,'auto browse schedules first tick');
t.fn();
assert.equal(current,1);
auto.restart();
assert.equal(auto.isEnabled(),true,'manual batch/word navigation must retain auto mode');
auto.stop();
assert.equal(auto.isEnabled(),false);
assert.ok(updates.length>=8);
console.log('PASS: question/answer face persists across navigation; auto mode survives restart; no SRS');
