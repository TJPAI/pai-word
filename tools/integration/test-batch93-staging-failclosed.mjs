import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {validateApprovedOverlay} from '../../scripts/core20k-approved-teaching-overlay.mjs';
import {createApprovedTeachingMap} from '../../scripts/approved-teaching-release-gate.mjs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const handoff=read('tools/integration/batch93-dual-ai-handoff.v1.json');
assert.equal(handoff.semantic_certified_ku_ids.length,6);
assert.equal(handoff.sense_binding_registered,true);
assert.equal(handoff.formal_release_activated,false);
assert.equal(handoff.staging_only,true);
const manifest=read('rebuild-preview/batch93-overlay-release-candidate-manifest.json');
const review=read('rebuild-preview/b218-isolated/B218_SIX_KU_TEACHING_CERTIFICATION_REVIEW.json');
const pack=read('rebuild-preview/b218-isolated/batch93_nonrelease_teaching_pack.json');
const readiness=execFileSync(process.execPath,['tools/integration/check-batch93-release-readiness.mjs','--json'],{encoding:'utf8'});
const parsed=JSON.parse(readiness.slice(readiness.indexOf('{'),readiness.lastIndexOf('}')+1));
assert.equal(parsed.production_activation_ready,false);
assert(parsed.remaining_gates.includes('production_manifest'));
assert(parsed.remaining_gates.includes('license_approved'));
assert(parsed.remaining_gates.includes('release_signed'));
assert(parsed.remaining_gates.includes('crosswalk_membership'));
assert(parsed.remaining_gates.includes('registrar_signed'));
assert(parsed.remaining_gates.includes('record_flags_ready'));
assert.equal(manifest.status,'STAGING_ONLY');
assert.equal(manifest.activation_allowed,false);
assert.equal(review.certification_status,'CONDITIONAL_PASS_PENDING_GRADING_IMPLEMENTATION_AND_SOURCE_ATTESTATION');
assert.equal(review.semantic_pass_count,6);
assert.equal(pack.records.length,6);
assert(pack.records.every(x=>x.content_certified===false&&x.production_ready===false));
assert.deepEqual(manifest.ku_ids,[...new Set(pack.records.map(x=>x.ku_id))]);
assert.deepEqual(handoff.semantic_certified_ku_ids,manifest.ku_ids);
assert.equal(manifest.authority.registrar_signed,false);
assert.equal(manifest.authority.license_approved,false);
assert.equal(manifest.authority.release_signed,false);
assert.equal(manifest.reviewed_crosswalk.length,0);
const forbidden=createApprovedTeachingMap({status:manifest.status,production_ready:false,activation:{allowed:false},source_rights_cleared:false,official_membership_verified:false,records:pack.records});
assert.equal(forbidden.enabled,false);
const overlay={schema_version:'pai-core20k-approved-overlay-v1',records:pack.records,version:manifest.version,runtime_sha256:manifest.runtime_sha256,pack_sha256:manifest.pack_sha256};
const validation=validateApprovedOverlay({base:{byKU:new Map()},overlay,manifest,enabled:true,verifiedRuntimeSha256:manifest.runtime_sha256,verifiedPackSha256:manifest.pack_sha256});
assert.equal(validation.enabled,false);
assert.equal(validation.reason,'release_gate');
console.log('PASS Batch93 six reviewed KUs stay staging only; both release gates fail closed');
