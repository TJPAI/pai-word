import assert from 'node:assert/strict';
import {createScene500NativeCursorProbe as make} from './scene500-native-cursor-persistence-harness.mjs';
const store=new Map();
const p=make({storage:store});
assert.equal(p.storageKey,'v22-integration:pai-word-preview-v2-scene-cursors');
assert.equal(p.writes.length,0,'Navigation is in-memory before background');
p.capture();
assert.equal(p.writes.length,0,'Capture must not flush localStorage during navigation');
assert.equal(p.get().page,'answer');
assert.equal(p.get().ku_id,'SCENE500_TEST_KU_001');
p.setKU('SCENE500_TEST_KU_003');p.setBrowsed('SCENE500_TEST_KU_004');
p.capture();
assert.equal(p.get().ku_id,'SCENE500_TEST_KU_004','Visible browsed KU takes precedence');
assert.equal(p.writes.length,0);
p.pagehide();
assert.equal(p.writes.length,1,'Pagehide durably saves cursor');
const snapshot=JSON.parse(store.get(p.storageKey));
assert.equal(snapshot.schema,2);
assert.equal(snapshot.last_scene_id,'SC50-0001');
assert.equal(snapshot.scenes['SC50-0001'].ku_id,'SCENE500_TEST_KU_004');
assert.equal(snapshot.scenes['SC50-0001'].page,'answer');
assert.equal(snapshot.scenes['SC50-0001'].mode,'normal');
assert.equal(snapshot.scenes['SC50-0001'].queue.length,2);
p.setBrowsed(null);p.setScene('SC50-0002');p.setKU('SCENE500_TEST_KU_005');p.setFace('QUESTION');
p.state.autoBrowseEnabled=true;
p.capture();
assert.equal(p.writes.length,1);
p.background();
assert.equal(p.writes.length,2,'Safari background saves bookmark');
const two=JSON.parse(store.get(p.storageKey));
assert.equal(two.last_scene_id,'SC50-0002');
assert.equal(two.scenes['SC50-0002'].page,'question');
assert.equal(two.scenes['SC50-0002'].mode,'auto');
assert.equal(two.scenes['SC50-0001'].page,'answer','Other scene cursor persists');
p.foreground();assert.equal(p.writes.length,2,'Foreground cannot overwrite cursor');
const reloaded=make({storage:store,scene:'SC50-0002',face:'QUESTION'});
assert.equal(reloaded.get().ku_id,'SCENE500_TEST_KU_005');
assert.equal(reloaded.window.PAI_LEARNING_CURSOR('SC50-0001').ku_id,'SCENE500_TEST_KU_004');
assert.equal(reloaded.window.PAI_RECENT_LEARNING_SCENE(),'SC50-0002');
assert(p.reads.every(key=>key===p.storageKey));
assert(p.writes.every(x=>x.key===p.storageKey));
assert.equal(p.writes.length,2,'Only bookmark writes, no SRS writes');
const prod=make({storage:new Map(),pathname:'/pai-word-preview/'});
assert.equal(prod.storageKey,'pai-word-preview-v2-scene-cursors');
assert.notEqual(prod.storageKey,p.storageKey,'Preview namespacing remains distinct');
console.log(JSON.stringify({status:'PASS',source:'exact Scene500 cursor implementation',
 cases:['answer-face bookmark','browse cursor precedence','in-memory until pagehide','background flush','multi-scene resume','auto-mode cursor','separate preview key'],
 bookmarkWrites:p.writes.length,srsWrites:0,quarantinedScene1341Activated:false}));
