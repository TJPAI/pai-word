import assert from 'node:assert/strict';
import {actionObjectCandidates,compareActionObjectCandidates} from '../experimental-action-object.mjs';
const ids=['S034','S037','S041','S113','S114','S275','S296'];
const catalog={scenes:Object.fromEntries(ids.map(x=>[x,{name:x,quality:'draft_unverified'}]))};
const get=q=>actionObjectCandidates(q,{catalog}).map(x=>x.sceneId);
assert.deepEqual(get('I want to order noodles for lunch'),['S034']);
assert.deepEqual(get("I'm allergic to peanuts"),['S037']);
assert.deepEqual(get('The waiter gave me the wrong bill'),['S041']);
assert.deepEqual(get('I need to book a hotel room'),['S113']);
assert.deepEqual(get('Where do I collect my hotel room key?'),['S114']);
assert.deepEqual(get('My phone app keeps crashing'),['S275']);
assert.deepEqual(get("I'm building a mobile app"),['S296']);
assert.deepEqual(get('I need to cancel my hotel booking'),[]);
assert.deepEqual(get('How do I update my app?'),[]);
assert.deepEqual(get('English pronunciation training'),[]);
assert.deepEqual(actionObjectCandidates('I want to order noodles',{catalog,eligibleSceneIds:['S037']}),[]);
const base={results:[{sceneId:'S113',score:5,reason:['baseline']}]};
const before=JSON.stringify(base);
const comparison=compareActionObjectCandidates(base,'I want to order noodles for lunch',{catalog,limit:10});
assert.equal(comparison.results[0].sceneId,'S034');
assert.equal(comparison.baseline[0].sceneId,'S113');
assert.equal(JSON.stringify(base),before);
assert.equal(compareActionObjectCandidates(base,'I want to order noodles for lunch',{catalog,limit:1}).results.length,1);
console.log('PASS_SCENE500_ACTION_OBJECT_EXPERIMENT: 14 positive/negative and isolation assertions');
